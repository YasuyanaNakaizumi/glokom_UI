export const tLegacyMaster = (
  lang: Language,
  kind: LegacyMasterKind,
  id: string,
  field: LegacyMasterField,
  fallback: string
): string => {
  const key = legacyMasterTranslations[kind]?.[id]?.[field];
  if (key) return t(lang, key);

  const translatedFallback = t(lang, fallback);
  return translatedFallback !== fallback ? translatedFallback : fallback;
};

/**
 * ドット区切りキーで翻訳文字列を取得します。
 * 存在しないキーの場合はキー文字列をそのまま返します。
 * パラメータは {{key}} 形式で埋め込めます。
 */
export const t = (
  lang: Language,
  key: string,
  params?: Record<string, string | number>
): string => {
  const resolve = (lookupKey: string) => {
    const keys = lookupKey.split('.');
    let value: any = i18nData[lang];
    for (const k of keys) {
      value = value?.[k];
    }
    return typeof value === 'string' ? value : undefined;
  };

  const value = resolve(key) ?? resolve(`sample.${key}`) ?? resolve(`views.${key}`);
  if (!value) return key;
  if (params) {
    return value.replace(/\{\{(\w+)\}\}/g, (_, name) =>
      String(params[name] ?? `{{${name}}}`)
    );
  }
  return value;
};

/**
 * types.ts で定義されている列挙値（内部値は日本語のまま）を
 * 現在の言語用の表示文字列に変換します。
 */
export const tEnum = (
  lang: Language,
  category: EnumCategory,
  value: string
): string => {
  const map = i18nData[lang].enum[category] as Record<string, string>;
  return map?.[value] ?? value;
};

